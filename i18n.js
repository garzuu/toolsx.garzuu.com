function currentLocale() {
  const stored = localStorage.getItem("toolsx-locale");
  if (stored && T[stored]) return stored;
  return (navigator.language || "en").toLowerCase().startsWith("it") ? "it" : "en";
}

function applyLocale(loc) {
  document.documentElement.lang = loc;
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (T[loc][key] !== undefined) el.innerHTML = T[loc][key];
  });
  const btn = document.getElementById("lang-toggle");
  if (btn) btn.textContent = loc === "it" ? "EN" : "IT";
}

function toggleLocale() {
  const next = currentLocale() === "it" ? "en" : "it";
  localStorage.setItem("toolsx-locale", next);
  applyLocale(next);
}

document.addEventListener("DOMContentLoaded", () => applyLocale(currentLocale()));
